/**
 * Primary Service Method: Retrieves or generates Grand Prix winner prediction.
 */
export async function getRacePrediction(
  rawRaceId: string,
  options: { forceRefresh?: boolean; simulate?: boolean; stage?: SnapshotStage } = {}
): Promise<RacePredictionResponse> {
  const { canonicalRaceId, season, round } = parseAndValidateRaceId(rawRaceId);
  const expectedCircuit = getCircuitForRound(season, round);

  // Check if an identical request is already computing (Concurrency Deduplication)
  const inFlightKey = `${canonicalRaceId}:${options.forceRefresh ? 'refresh' : 'standard'}:${options.simulate ? 'sim' : 'live'}:${options.stage || 'all'}`;
  if (inFlightRequests.has(inFlightKey)) {
    return inFlightRequests.get(inFlightKey)!;
  }

  const executionPromise: Promise<RacePredictionResponse> = (async (): Promise<RacePredictionResponse> => {
    try {
      // 1. Snapshot-First Resolution: Model binary verification belongs authoritatively to the Python
      // inference runner. The TypeScript service verifies snapshot data contracts and cryptographic hashes.
      // Dynamic Python execution is only attempted if valid pre-computed snapshots are unavailable.

      // 2. Check for Cached Prediction in Memory (validated against identity & schema)
      const memoryCandidates: RacePredictionResponse[] = [];
      if (!options.forceRefresh) {
        for (const [key, cached] of memorySnapshotCache.entries()) {
          if (key.startsWith(`${canonicalRaceId}:${MODEL_VERSION}:`)) {
            const valResult = validateSnapshot(cached, season, round, expectedCircuit?.circuitId, { allowLegacy: season <= 2024 });
            if (valResult.valid) {
              if (!cached.stage && valResult.stage) {
                cached.stage = valResult.stage;
              }
              if (!options.stage || cached.stage === options.stage) {
                memoryCandidates.push(cached);
              }
            } else {
              memorySnapshotCache.delete(key);
            }
          }
        }
        if (memoryCandidates.length > 0) {
          memoryCandidates.sort((a, b) => compareSnapshotPrecedence(b, a));
          // If the top memory candidate is official_grid or matches requested stage, return immediately
          if (options.stage || memoryCandidates[0].stage === 'official_grid') {
            let enriched = enrichPredictionWithTrackHeritage({ ...memoryCandidates[0], cached: true }, memoryCandidates[0].circuitId);
            if (season === 2026 && !enriched.regulationEraWarning) {
              enriched = { ...enriched, regulationEraWarning: REGULATION_ERA_WARNING_2026 };
            }
            return enriched;
          }
        }
      }

      // 3. Explicit simulation mode (user exploring pre-race scenarios)
      if (options.simulate) {
        const sim = generateProvisionalSimulation(season, round, expectedCircuit?.circuitId);
        if (season === 2026 && !sim.regulationEraWarning) {
          sim.regulationEraWarning = REGULATION_ERA_WARNING_2026;
        }
        return sim;
      }

      // 4. Check for Authoritative Cloud Snapshot in Supabase (if configured)
      const cloudCandidates: RacePredictionResponse[] = [];
      if (!options.forceRefresh && isSupabaseConfigured()) {
        try {
          const supabasePromise = supabase
            .from('race_prediction_snapshots')
            .select('*')
            .eq('race_id', canonicalRaceId)
            .eq('model_version', MODEL_VERSION)
            .order('generated_at', { ascending: false })
            .limit(5);

          const timeoutPromise = new Promise<{ data: null; error: any }>((resolve) =>
            setTimeout(() => resolve({ data: null, error: new Error('Supabase query timed out') }), 1500)
          );

          const { data } = await Promise.race([supabasePromise, timeoutPromise]);

          if (Array.isArray(data)) {
            for (const row of data) {
              if (row && row.predictions_payload) {
                const rowStage: SnapshotStage = (row.prediction_stage === 'official_grid' || row.prediction_stage === 'provisional')
                  ? row.prediction_stage
                  : (row.qualifying_status === 'completed' ? 'official_grid' : 'provisional');

                const restored: RacePredictionResponse = {
                  status: row.status,
                  raceId: row.race_id,
                  season: row.season,
                  round: row.round,
                  circuitId: row.circuit_id,
                  circuitName: row.circuit_name,
                  country: row.country || expectedCircuit?.country,
                  stage: rowStage,
                  predictionStage: 'after_qualifying',
                  generatedAtUtc: row.generated_at,
                  modelVersion: row.model_version,
                  featureSchemaVersion: row.feature_schema_version || FEATURE_SCHEMA_VERSION,
                  inputHash: row.input_hash,
                  qualifyingStatus: {
                    isCompleted: row.qualifying_status === 'completed',
                    freshness: 'historical',
                    totalClassified: row.predictions_payload.length,
                    hasPenaltiesApplied: rowStage === 'official_grid',
                    dataCompletenessPct: 100
                  },
                  provenance: {
                    qualifyingSource: 'supabase_snapshot',
                    baselineVersion: 'v1.3.1',
                    retrievalTimestampUtc: row.generated_at
                  },
                  expectedRoster: row.season === 2026 ? CURRENT_2026_GRID.map(d => d.driverId) : undefined,
                  predictedWinner: row.predicted_winner_id ? {
                    driverId: row.predicted_winner_id,
                    driverCode: row.predicted_winner_code,
                    winProbability: Number(row.predicted_winner_prob),
                    winProbabilityPct: Math.round(Number(row.predicted_winner_prob) * 10000) / 100,
                    constructorName: '',
                    gridPosition: 1
                  } : null,
                  predictions: row.predictions_payload,
                  topExplanatoryFactors: row.explanatory_factors || [],
                  cached: true,
                  immutableSnapshotId: row.id,
                  causalDisclaimer: 'Historical snapshot predictions reflect verified pre-race conditions.'
                };

                if (row.season === 2026) {
                  restored.regulationEraWarning = REGULATION_ERA_WARNING_2026;
                }

                const val = validateSnapshot(restored, season, round, expectedCircuit?.circuitId, { allowLegacy: season <= 2024 });
                if (val.valid) {
                  if (!options.stage || restored.stage === options.stage) {
                    cloudCandidates.push(restored);
                  }
                } else {
                  console.warn(`[Snapshot Security] Rejected invalid Supabase snapshot for '${canonicalRaceId}': ${val.reason}`);
                }
              }
            }
          }
        } catch {
          // Continue to disk/live resolution
        }
      }

      // 5. Check Local Disk Snapshot (validated)
      const diskSnapshot = (!options.forceRefresh)
        ? loadAndValidateDiskSnapshot(canonicalRaceId, season, round, expectedCircuit?.circuitId, {
            allowLegacy: season <= 2024,
            stage: options.stage
          })
        : null;

      // Safe Precedence Evaluation across memory, cloud, and disk
      const allCandidates: RacePredictionResponse[] = [...memoryCandidates, ...cloudCandidates];
      if (diskSnapshot) {
        allCandidates.push(diskSnapshot.response);
      }

      if (allCandidates.length > 0) {
        allCandidates.sort((a, b) => compareSnapshotPrecedence(b, a));
        const winner = allCandidates[0];
        let enriched = enrichPredictionWithTrackHeritage({ ...winner, cached: true }, winner.circuitId);
        if (season === 2026 && !enriched.regulationEraWarning) {
          enriched = { ...enriched, regulationEraWarning: REGULATION_ERA_WARNING_2026 };
        }
        const stageKey = enriched.stage || (enriched.qualifyingStatus?.hasPenaltiesApplied ? 'official_grid' : 'provisional');
        const cacheKey = `${canonicalRaceId}:${MODEL_VERSION}:${FEATURE_SCHEMA_VERSION}:${stageKey}:${enriched.inputHash}`;
        memorySnapshotCache.set(cacheKey, enriched);
        return enriched;
      }

      // 5b. Stage fail-closed guard: if official_grid was specifically requested and no official_grid snapshot exists,
      // return unavailable immediately rather than falling back to live qualifying, simulation, or provisional snapshot.
      if (options.stage === 'official_grid') {
        return {
          status: 'unavailable' as const,
          raceId: canonicalRaceId,
          season,
          round,
          circuitId: expectedCircuit?.circuitId || 'unknown',
          circuitName: expectedCircuit?.circuitName || 'Grand Prix Circuit',
          country: expectedCircuit?.country || 'International',
          stage: 'official_grid' as const,
          predictionStage: 'official_grid' as const,
          generatedAtUtc: new Date().toISOString(),
          modelVersion: MODEL_VERSION,
          featureSchemaVersion: FEATURE_SCHEMA_VERSION,
          inputHash: 'none',
          qualifyingStatus: {
            isCompleted: false,
            freshness: 'not_started' as const,
            totalClassified: 0,
            hasPenaltiesApplied: false,
            dataCompletenessPct: 0
          },
          regulationEraWarning: season === 2026 ? REGULATION_ERA_WARNING_2026 : undefined,
          predictedWinner: null,
          predictions: [],
          topExplanatoryFactors: [],
          cached: false,
          error: 'OFFICIAL_GRID_SNAPSHOT_NOT_FOUND',
          message: `Official starting grid snapshot for ${season} Round ${round} is not available. Predictions strictly lock after official grid publication.`,
          causalDisclaimer: ''
        };
      }

      // 6. Modern championship session gating (held in authentic pre-qualifying state if session not yet held)
      if (season >= 2025) {
        return {
          status: 'unavailable' as const,
          raceId: canonicalRaceId,
          season,
          round,
          circuitId: expectedCircuit?.circuitId || 'unknown',
          circuitName: expectedCircuit?.circuitName || 'Grand Prix Circuit',
          country: expectedCircuit?.country || 'International',
          stage: 'provisional' as const,
          predictionStage: 'after_qualifying' as const,
          generatedAtUtc: new Date().toISOString(),
          modelVersion: MODEL_VERSION,
          featureSchemaVersion: FEATURE_SCHEMA_VERSION,
          inputHash: 'none',
          qualifyingStatus: {
            isCompleted: false,
            freshness: 'not_started' as const,
            totalClassified: 0,
            hasPenaltiesApplied: false,
            dataCompletenessPct: 0
          },
          regulationEraWarning: season === 2026 ? REGULATION_ERA_WARNING_2026 : undefined,
          predictedWinner: null,
          predictions: [],
          topExplanatoryFactors: [],
          cached: false,
          error: 'QUALIFYING_NOT_COMPLETED',
          message: `Qualifying session for ${season} Round ${round} has not yet taken place. Predictions unlock strictly post-qualifying.`,
          causalDisclaimer: ''
        };
      }

      // 6b. Check Live Jolpi.ca / Ergast Qualifying Telemetry Feed
      // If qualifying has concluded and results are published on the FIA API, ingest and generate predictions
      const liveQuali = await fetchLiveQualifyingFromJolpica(season, round);
      if (liveQuali) {
        const livePrediction = generatePredictionsFromQualifyingResults(
          season,
          round,
          liveQuali.raceName,
          liveQuali.circuitId,
          liveQuali.circuitName,
          liveQuali.country,
          liveQuali.results
        );
        await persistPredictionSnapshot(canonicalRaceId, livePrediction);
        return livePrediction;
      }

      // 7. Execute Prediction through Python Inference CLI
      const pythonBin = getPythonExecutable();

      let stdout = '';
      try {
        const res = await execFileAsync(pythonBin, [
          '-m',
          'scripts.predictor_model.inference',
          '--race-id',
          canonicalRaceId
        ], {
          cwd: PROJECT_ROOT,
          timeout: 15000,
          env: {
            ...process.env,
            PYTHONPATH: PROJECT_ROOT
          }
        });
        stdout = res.stdout;
      } catch (execErr: any) {
        stdout = execErr?.stdout || '';
      }

      let parsedResult: any;
      try {
        const trimmed = stdout.trim();
        const jsonStart = trimmed.indexOf('{');
        const jsonEnd = trimmed.lastIndexOf('}');
        if (jsonStart !== -1 && jsonEnd !== -1 && jsonEnd >= jsonStart) {
          parsedResult = JSON.parse(trimmed.slice(jsonStart, jsonEnd + 1));
        } else {
          parsedResult = JSON.parse(trimmed);
        }
      } catch {
        const validDisk = loadAndValidateDiskSnapshot(canonicalRaceId, season, round, expectedCircuit?.circuitId);
        if (validDisk) {
          const enriched = enrichPredictionWithTrackHeritage({ ...validDisk.response, cached: false }, validDisk.response.circuitId);
          memorySnapshotCache.set(`${canonicalRaceId}:${MODEL_VERSION}:${validDisk.response.inputHash}`, enriched);
          return enriched;
        }

        const isUnknownRace = season < 1950 || season > 2030 || round < 1 || round > 25 || (season === 1950 && round > 7);
        return {
          status: 'unavailable' as const,
          raceId: canonicalRaceId,
          season,
          round,
          circuitId: isUnknownRace ? 'unknown' : (expectedCircuit?.circuitId || 'unknown'),
          circuitName: isUnknownRace ? 'Unknown Grand Prix' : (expectedCircuit?.circuitName || 'Grand Prix Circuit'),
          country: isUnknownRace ? 'International' : (expectedCircuit?.country || 'International'),
          predictionStage: 'after_qualifying' as const,
          generatedAtUtc: new Date().toISOString(),
          modelVersion: MODEL_VERSION,
          featureSchemaVersion: FEATURE_SCHEMA_VERSION,
          inputHash: 'none',
          qualifyingStatus: {
            isCompleted: false,
            freshness: 'not_started' as const,
            totalClassified: 0,
            hasPenaltiesApplied: false,
            dataCompletenessPct: 0
          },
          predictedWinner: null,
          predictions: [],
          topExplanatoryFactors: [],
          cached: false,
          error: isUnknownRace ? 'RACE_NOT_FOUND' : 'QUALIFYING_NOT_COMPLETED',
          message: isUnknownRace ? `Race ${canonicalRaceId} was not found in official F1 records.` : 'Official qualifying session data is not yet finalized.',
          causalDisclaimer: ''
        };
      }

      if (parsedResult.status === 'error' || parsedResult.error_type === 'RACE_NOT_FOUND') {
        const validDisk = loadAndValidateDiskSnapshot(canonicalRaceId, season, round, expectedCircuit?.circuitId);
        if (validDisk) {
          const enriched = enrichPredictionWithTrackHeritage({ ...validDisk.response, cached: false }, validDisk.response.circuitId);
          memorySnapshotCache.set(`${canonicalRaceId}:${MODEL_VERSION}:${validDisk.response.inputHash}`, enriched);
          return enriched;
        }
        return {
          status: 'unavailable' as const,
          raceId: canonicalRaceId,
          season,
          round,
          circuitId: expectedCircuit?.circuitId || 'unknown',
          circuitName: expectedCircuit?.circuitName || 'Unknown Grand Prix',
          country: expectedCircuit?.country || 'International',
          predictionStage: 'after_qualifying' as const,
          generatedAtUtc: new Date().toISOString(),
          modelVersion: MODEL_VERSION,
          featureSchemaVersion: FEATURE_SCHEMA_VERSION,
          inputHash: 'none',
          qualifyingStatus: {
            isCompleted: false,
            freshness: 'not_started' as const,
            totalClassified: 0,
            hasPenaltiesApplied: false,
            dataCompletenessPct: 0
          },
          predictedWinner: null,
          predictions: [],
          topExplanatoryFactors: [],
          cached: false,
          error: parsedResult.error_type || 'RACE_UNAVAILABLE',
          message: parsedResult.message || `No verified post-qualifying session found for '${canonicalRaceId}'.`,
          causalDisclaimer: ''
        };
      }

      // 8. Compute Input Hash & Attach Invariant Validation
      const inputHash = computeInputHash(parsedResult.predictions.map((p: any) => ({
        driverId: p.driverId,
        gridPosition: p.gridPosition,
        qualiPosition: p.qualiPosition
      })));

      const response: RacePredictionResponse = {
        ...parsedResult,
        inputHash,
        cached: false
      };

      const enrichedResponse = enrichPredictionWithTrackHeritage(response, response.circuitId || expectedCircuit?.circuitId || 'americas');
      validatePredictionInvariants(enrichedResponse);

      // 9. Save Immutable Snapshot
      const snapshotId = await persistPredictionSnapshot(canonicalRaceId, enrichedResponse);
      enrichedResponse.immutableSnapshotId = snapshotId;

      return enrichedResponse;
    } finally {
      inFlightRequests.delete(inFlightKey);
    }
  })();

  inFlightRequests.set(inFlightKey, executionPromise);
  return executionPromise;
}
