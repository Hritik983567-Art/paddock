def run_dry_run_inference(
    race_id: str,
    stage: str = "provisional",
    output_dir: Optional[str] = None,
    baseline_path: Optional[str] = None,
    model_bundle_path: Optional[str] = None,
    metadata_path: Optional[str] = None,
    dry_run: bool = True,
    mode: str = "standard"
) -> Dict[str, Any]:
    """
    Executes dry-run prediction snapshot generation for an explicit historical race.
    Supports both mode='standard' (Phase 3C.4B) and mode='hybrid' (Phase 3C.4F.3).
    """
    if mode == "hybrid":
        return run_dry_run_hybrid_inference(
            race_id=race_id,
            stage=stage,
            output_dir=output_dir,
            baseline_path=baseline_path,
            dry_run=dry_run
        )

    if not dry_run:
        raise RunnerError("LIVE_WRITES_FORBIDDEN", "Phase 3C.4B permits only dry-run execution. Pass dry_run=True.")

    stage_clean = stage.strip().lower()
    if stage_clean != "provisional":
        raise RunnerError(
            "UNSUPPORTED_STAGE",
            f"Unsupported stage '{stage}'. Phase 3C.4B dry-run runner supports only '--stage provisional'."
        )

    # 1. Parse and validate race ID
    season, round_num, circuit_hint = parse_race_id(race_id)

    # 2. Safety: Validate output directory
    resolved_output_dir = os.path.abspath(output_dir or os.path.join(PROJECT_ROOT, "artifacts", "dry_run_snapshots"))
    prod_snapshot_dir = os.path.abspath(os.path.join(PROJECT_ROOT, "data", "predictor", "snapshots"))

    if resolved_output_dir == prod_snapshot_dir or resolved_output_dir.startswith(prod_snapshot_dir + os.sep):
        raise RunnerError(
            "FORBIDDEN_OUTPUT_DIRECTORY",
            f"Refusing to write dry-run artifacts into production snapshot directory '{prod_snapshot_dir}'."
        )
    os.makedirs(resolved_output_dir, exist_ok=True)

    # 3. Model & Feature Contract Verification
    lgb_model, metadata = load_and_verify_model_bundle(model_bundle_path, metadata_path)

    # 4. LiveFeatureBuilder Assembly from Historical Baseline
    default_baseline = os.path.join(OUTPUT_DIR, "historical_baseline_2025_2026.json")
    resolved_baseline = baseline_path or default_baseline

    if not os.path.exists(resolved_baseline):
        raise RunnerError("BASELINE_FILE_MISSING", f"Historical baseline file not found at '{resolved_baseline}'.")

    builder = LiveFeatureBuilder(baseline_path=resolved_baseline, validate_schema=True)

    try:
        feature_result: LiveFeatureResult = builder.build_features_for_race(
            season=season,
            round_num=round_num,
            stage=stage_clean
        )
    except LiveFeatureBuilderError as e:
        raise RunnerError(e.error_type, e.message, e.details)

    features_df = feature_result.features_df
    metadata_df = feature_result.metadata_df
    diagnostics = feature_result.diagnostics

    # Assert exactly 42 features in exact order
    if list(features_df.columns) != ALL_MODEL_FEATURES:
        raise RunnerError(
            "FEATURE_CONTRACT_VIOLATION",
            f"LiveFeatureBuilder generated {len(features_df.columns)} features; expected exact 42 features matching ALL_MODEL_FEATURES."
        )

    # 5. Calibrated Model Inference (Temperature T=1.85)
    try:
        probs = lgb_model.predict_race_probabilities(features_df, temperature=1.85)
    except Exception as e:
        raise RunnerError("INFERENCE_FAILED", f"Model predict_race_probabilities execution failed: {str(e)}")

    if not np.all(np.isfinite(probs)):
        raise RunnerError("NON_FINITE_PROBABILITIES", "Model produced non-finite probability values.")
    if np.any(probs < 0.0) or np.any(probs > 1.0):
        raise RunnerError("PROBABILITY_OUT_OF_BOUNDS", "Model produced probabilities outside [0, 1].")

    # 6. Assemble Canonical Prediction Entries
    first_meta = metadata_df.iloc[0]
    canonical_race_id = str(first_meta["race_id"])
    circuit_id = str(first_meta["circuit_id"])
    circuit_name = str(first_meta["circuit_name"])
    country = str(first_meta["country"])

    driver_entries: List[Dict[str, Any]] = []
    driver_feature_records: List[Dict[str, Any]] = []
    for idx, (_, meta_row) in enumerate(metadata_df.iterrows()):
        p_val = float(probs[idx])
        d_id = str(meta_row["driver_id"])
        driver_entry = {
            "driverId": d_id,
            "driverCode": str(meta_row["driver_code"]),
            "driverNumber": str(meta_row["driver_number"]),
            "constructorId": str(meta_row["constructor_id"]),
            "constructorName": str(meta_row["constructor_name"]),
            "gridPosition": int(features_df.iloc[idx]["grid_position"]),
            "qualiPosition": int(features_df.iloc[idx]["quali_position"]),
            "gridPenaltyDelta": 0,
            "winProbability": round(p_val, 4),
            "winProbabilityPct": round(p_val * 100.0, 2),
            "predictedRank": 0  # assigned after sorting
        }
        driver_entries.append(driver_entry)

        # Assemble full 42 features for canonical hashing
        feat_dict = {col: features_df.iloc[idx][col] for col in ALL_MODEL_FEATURES}
        driver_feature_records.append({
            "driver_id": d_id,
            "features": feat_dict
        })

    # Sort descending by win probability
    driver_entries.sort(key=lambda d: d["winProbability"], reverse=True)
    for rank, entry in enumerate(driver_entries, start=1):
        entry["predictedRank"] = rank

    winner = driver_entries[0]

    # Compute deterministic input hash from all material inputs
    inference_config = {
        "calibration": "temperature_scaling",
        "temperature": 1.85
    }
    input_hash = compute_input_hash(
        race_id=canonical_race_id,
        circuit_id=circuit_id,
        stage=stage_clean,
        model_version=MODEL_VERSION,
        feature_schema_version=FEATURE_SCHEMA_VERSION,
        baseline_version=CURRENT_CONTRACT_VERSION,
        feature_builder_version=FEATURE_BUILDER_VERSION,
        inference_config=inference_config,
        driver_features=driver_feature_records
    )

    # Timestamp
    gen_timestamp_utc = datetime.now(timezone.utc).isoformat()

    # Regulation era warning
    if season == 2026:
        reg_warning = REGULATION_ERA_WARNING_2026
    else:
        reg_warning = {
            "isUnknownRegulationEra": False,
            "regulationEra": diagnostics.get("regulation_era", get_regulation_era(season)),
            "warningCode": "HISTORICAL_VALIDATED",
            "disclaimer": "Model evaluated on verified historical ground truth under conforming regulation era."
        }

    # Top explanatory factors
    top_factors = metadata.get("explainability_summary", {}).get("top_shap_features", [])

    # Assemble canonical snapshot payload
    snapshot_payload: Dict[str, Any] = {
        "status": "success",
        "raceId": canonical_race_id,
        "season": season,
        "round": round_num,
        "circuitId": circuit_id,
        "circuitName": circuit_name,
        "country": country,
        "stage": "provisional",
        "predictionStage": "after_qualifying",
        "generatedAtUtc": gen_timestamp_utc,
        "modelVersion": MODEL_VERSION,
        "featureSchemaVersion": FEATURE_SCHEMA_VERSION,
        "inputHash": input_hash,
        "qualifyingStatus": {
            "isCompleted": True,
            "freshness": "dry_run",
            "totalClassified": len(driver_entries),
            "hasPenaltiesApplied": False,
            "dataCompletenessPct": 100.0
        },
        "provenance": {
            "qualifyingSource": diagnostics.get("qualifying_provenance", "historical_baseline_v1.3.1"),
            "baselineVersion": CURRENT_CONTRACT_VERSION,
            "retrievalTimestampUtc": diagnostics.get("cutoff_timestamp_utc", gen_timestamp_utc),
            "pipelineVersion": "3C.4B-dryrun"
        },
        "expectedRoster": [d["driverId"] for d in driver_entries],
        "regulationEraWarning": reg_warning,
        "validationStatus": "verified",
        "predictedWinner": {
            "driverId": winner["driverId"],
            "driverCode": winner["driverCode"],
            "winProbability": winner["winProbability"],
            "winProbabilityPct": winner["winProbabilityPct"],
            "constructorName": winner["constructorName"],
            "gridPosition": winner["gridPosition"]
        },
        "predictions": driver_entries,
        "topExplanatoryFactors": top_factors,
        "cached": False,
        "dryRun": True,
        "causalDisclaimer": (
            "Probabilities quantify statistical associations in historical post-qualifying Grand Prix data. "
            "They do not imply single-factor causal determinism without tyre management, car reliability, and race strategy."
        )
    }

    # 7. Fail-Closed Validation
    validate_dry_run_snapshot(snapshot_payload, require_all_fields=True)

    # 8. Atomic Local File Emission
    dest_filename = f"{canonical_race_id}_{stage_clean}_{MODEL_VERSION}_{input_hash}.json"
    dest_path = os.path.join(resolved_output_dir, dest_filename)

    if os.path.exists(dest_path):
        raise RunnerError(
            "OUTPUT_FILE_COLLISION",
            f"Output artifact already exists at '{dest_path}'. Overwriting existing snapshots is forbidden in dry-run mode."
        )

    temp_path = dest_path + f".tmp.{os.getpid()}"
    try:
        with open(temp_path, "w", encoding="utf-8") as f:
            json.dump(snapshot_payload, f, indent=2)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp_path, dest_path)
    except Exception as e:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise RunnerError("OUTPUT_WRITE_FAILED", f"Failed to atomically write output artifact: {str(e)}")

    return {
        "status": "success",
        "snapshot": snapshot_payload,
        "artifact_path": dest_path,
        "artifact_filename": dest_filename,
        "input_hash": input_hash,
        "predicted_winner": winner["driverId"],
        "winner_prob": winner["winProbability"]
    }


