def parse_race_id(raw_race_id: str) -> Tuple[int, int, Optional[str]]:
    """
    Parses and standardizes raceId strings.
    Supported examples: '2025_1', '2025-1', '2025/1', '2025_1_albert_park'
    """
    if not raw_race_id or not isinstance(raw_race_id, str):
        raise RunnerError("INVALID_RACE_ID", "Race ID must be a non-empty string.")

    cleaned = raw_race_id.strip()
    match = re.match(r"^(\d{4})[_\-\/](\d{1,2})(?:_([a-zA-Z0-9_\-]+))?$", cleaned)
    if not match:
        raise RunnerError(
            "INVALID_RACE_ID_FORMAT",
            f"Invalid race ID '{raw_race_id}'. Expected format like '2025_1' or '2025_1_albert_park'."
        )

    season = int(match.group(1))
    round_num = int(match.group(2))
    circuit_hint = match.group(3)

    if season < 1950 or season > 2030:
        raise RunnerError("INVALID_SEASON", f"Season {season} is outside supported range [1950, 2030].")
    if round_num < 1 or round_num > 35:
        raise RunnerError("INVALID_ROUND", f"Round {round_num} is outside physical bounds [1, 35].")

    return season, round_num, circuit_hint


def format_canonical_numeric(val: Any) -> str:
    """
    Produces deterministic string representation for numbers with 8 decimal places.
    Handles NaN and None as canonical 'NaN' and 'null'.
    Rejects Infinite values.
    """
    if val is None:
        return "null"
    try:
        f = float(val)
    except (ValueError, TypeError):
        return str(val)
    if math.isnan(f):
        return "NaN"
    if math.isinf(f):
        raise ValueError(f"Feature value must be finite; got {val}.")
    rounded = round(f, 8)
    return f"{rounded:.8f}"


def build_canonical_input_payload(
    race_id: str,
    circuit_id: str,
    stage: str,
    model_version: str,
    feature_schema_version: str,
    baseline_version: str,
    feature_builder_version: str,
    inference_config: Dict[str, Any],
    driver_features: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """
    Assembles a deterministic, canonical representation of all material inputs
    affecting prediction probabilities.
    """
    race_identity = {
        "circuit_id": str(circuit_id).strip().lower(),
        "race_id": str(race_id).strip().lower(),
    }

    versions = {
        "baseline_version": str(baseline_version).strip(),
        "feature_builder_version": str(feature_builder_version).strip(),
        "feature_schema_version": str(feature_schema_version).strip(),
        "model_version": str(model_version).strip(),
    }

    clean_config = {}
    for k in sorted(inference_config.keys()):
        val = inference_config[k]
        if isinstance(val, (int, float)) and not isinstance(val, bool):
            clean_config[k] = format_canonical_numeric(val)
        else:
            clean_config[k] = str(val)

    # Sort drivers deterministically by driver_id to guarantee roster ordering invariance
    sorted_drivers = sorted(
        driver_features,
        key=lambda d: str(d.get("driver_id", d.get("driverId", ""))).strip().lower()
    )

    clean_driver_records = []
    for d in sorted_drivers:
        d_id = str(d.get("driver_id", d.get("driverId", ""))).strip().lower()
        if not d_id:
            raise ValueError("Driver entry missing driver_id.")

        features_dict = d.get("features", {})
        if not isinstance(features_dict, dict):
            raise ValueError(f"Driver '{d_id}' features must be a dictionary.")

        clean_features = {}
        for f_name in sorted(features_dict.keys()):
            f_val = features_dict[f_name]
            if isinstance(f_val, (int, float)) and not isinstance(f_val, bool):
                clean_features[f_name] = format_canonical_numeric(f_val)
            else:
                clean_features[f_name] = str(f_val)

        clean_driver_records.append({
            "driver_id": d_id,
            "features": clean_features
        })

    return {
        "driver_features": clean_driver_records,
        "inference_config": clean_config,
        "race_identity": race_identity,
        "stage": str(stage).strip().lower(),
        "versions": versions,
    }


def compute_input_hash(
    race_id: Union[str, List[Dict[str, Any]]] = "unknown_race",
    circuit_id: str = "unknown_circuit",
    stage: str = "provisional",
    model_version: str = MODEL_VERSION,
    feature_schema_version: str = FEATURE_SCHEMA_VERSION,
    baseline_version: str = CURRENT_CONTRACT_VERSION,
    feature_builder_version: str = FEATURE_BUILDER_VERSION,
    inference_config: Optional[Dict[str, Any]] = None,
    driver_features: Optional[List[Dict[str, Any]]] = None,
    driver_rows: Optional[List[Dict[str, Any]]] = None
) -> str:
    """
    Computes deterministic SHA-256 hash (16 hex chars) of canonical inference inputs.
    Accounts for race identity, circuit, stage, versions, config, roster, and 42-feature matrix.
    Guarantees order independence of driver rows while being strictly sensitive to all material changes.
    """
    if isinstance(race_id, list):
        driver_list = race_id
        race_id_val = "legacy_compat_race"
    elif driver_features is not None:
        driver_list = driver_features
        race_id_val = str(race_id)
    elif driver_rows is not None:
        driver_list = driver_rows
        race_id_val = str(race_id)
    else:
        driver_list = []
        race_id_val = str(race_id)

    normalized_driver_features = []
    for d in driver_list:
        if "features" in d and isinstance(d["features"], dict):
            normalized_driver_features.append(d)
        else:
            d_id = d.get("driverId", d.get("driver_id", ""))
            feats = {k: v for k, v in d.items() if k not in ("driverId", "driver_id")}
            normalized_driver_features.append({"driver_id": d_id, "features": feats})

    cfg = inference_config or {"calibration": "temperature_scaling", "temperature": 1.85}

    canonical_payload = build_canonical_input_payload(
        race_id=race_id_val,
        circuit_id=circuit_id,
        stage=stage,
        model_version=model_version,
        feature_schema_version=feature_schema_version,
        baseline_version=baseline_version,
        feature_builder_version=feature_builder_version,
        inference_config=cfg,
        driver_features=normalized_driver_features
    )

    canonical_json = json.dumps(canonical_payload, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()[:16]


def load_and_verify_model_bundle(
    model_bundle_path: Optional[str] = None,
    metadata_path: Optional[str] = None
) -> Tuple[Any, Dict[str, Any]]:
    """
    Loads and validates the frozen model bundle and metadata artifact.
    """
    default_bundle = os.path.join(MODELS_ROOT_DIR, MODEL_VERSION, "trained_models.joblib")
    default_meta = os.path.join(MODELS_ROOT_DIR, MODEL_VERSION, "model_metadata.json")

    bundle_path = model_bundle_path or default_bundle
    meta_path = metadata_path or default_meta

    if not os.path.exists(bundle_path):
        raise RunnerError("MODEL_ARTIFACT_MISSING", f"Trained model bundle not found at {bundle_path}")
    if not os.path.exists(meta_path):
        raise RunnerError("METADATA_MISSING", f"Model metadata not found at {meta_path}")

    # Load and verify metadata
    with open(meta_path, "r", encoding="utf-8") as f:
        metadata = json.load(f)

    meta_model_version = metadata.get("model_version")
    meta_feature_version = metadata.get("feature_schema_version")

    if meta_model_version != MODEL_VERSION:
        raise RunnerError(
            "MODEL_VERSION_MISMATCH",
            f"Metadata model_version '{meta_model_version}' does not match system version '{MODEL_VERSION}'."
        )
    if meta_feature_version != FEATURE_SCHEMA_VERSION:
        raise RunnerError(
            "FEATURE_SCHEMA_MISMATCH",
            f"Metadata feature_schema_version '{meta_feature_version}' does not match system version '{FEATURE_SCHEMA_VERSION}'."
        )

    # Verify exact binary integrity of frozen model bundle before loading
    EXPECTED_BUNDLE_SHA256 = "D8244024E6B7F0F31912EFE80B35652EF228461955232DDE7E4D65ECCC5779CD"
    with open(bundle_path, "rb") as f:
        actual_sha256 = hashlib.sha256(f.read()).hexdigest().upper()
    if actual_sha256 != EXPECTED_BUNDLE_SHA256:
        raise RunnerError(
            "MODEL_ARTIFACT_TAMPERED",
            f"Frozen model artifact SHA-256 mismatch! Expected {EXPECTED_BUNDLE_SHA256}, got {actual_sha256}."
        )

    # Load trained model bundle
    try:
        models = joblib.load(bundle_path)
    except Exception as e:
        py_ver = sys.version.split()[0]
        raise RunnerError(
            "INCOMPATIBLE_RUNTIME",
            f"Failed to deserialize model bundle under Python {py_ver}: {str(e)}."
        )

    lgb_model = models.get("lightgbm")
    if lgb_model is None:
        raise RunnerError("MODEL_CORRUPT", "LightGBM model candidate missing from joblib bundle.")

    return lgb_model, metadata


def validate_dry_run_snapshot(snapshot: Dict[str, Any], require_all_fields: bool = False) -> None:
    """
    Enforces the canonical Phase 3C.4A contract on candidate snapshot dictionary.
    Fails closed on any invariant deviation.
    """
    if not isinstance(snapshot, dict):
        raise SnapshotValidationError("PAYLOAD_INVALID", "Snapshot is not a dictionary.")

    # 0. Required Top-Level Fields (when require_all_fields=True)
    if require_all_fields:
        required_fields = [
            "status", "raceId", "season", "round", "circuitId", "circuitName",
            "country", "stage", "predictionStage", "modelVersion",
            "featureSchemaVersion", "inputHash", "generatedAtUtc",
            "qualifyingStatus", "provenance", "expectedRoster",
            "predictions", "predictedWinner"
        ]
        for rf in required_fields:
            if rf not in snapshot or snapshot[rf] is None:
                raise SnapshotValidationError("MISSING_REQUIRED_FIELD", f"Snapshot missing required field '{rf}'.")

    # 1. Identity & Contract Versions
    if snapshot.get("status") not in ("success", "provisional"):
        raise SnapshotValidationError("INVALID_STATUS", f"Invalid status '{snapshot.get('status')}'.")
    if not isinstance(snapshot.get("season"), int) or not isinstance(snapshot.get("round"), int):
        raise SnapshotValidationError("INVALID_RACE_IDENTITY", "Season and round must be integers.")
    if not snapshot.get("circuitId") or not isinstance(snapshot.get("circuitId"), str):
        raise SnapshotValidationError("INVALID_CIRCUIT_ID", "circuitId must be a non-empty string.")
    if snapshot.get("modelVersion") != MODEL_VERSION:
        raise SnapshotValidationError(
            "MODEL_VERSION_MISMATCH",
            f"modelVersion '{snapshot.get('modelVersion')}' must be '{MODEL_VERSION}'."
        )
    if snapshot.get("featureSchemaVersion") != FEATURE_SCHEMA_VERSION:
        raise SnapshotValidationError(
            "FEATURE_SCHEMA_MISMATCH",
            f"featureSchemaVersion '{snapshot.get('featureSchemaVersion')}' must be '{FEATURE_SCHEMA_VERSION}'."
        )

    # Input Hash Check & Dual-Hash / Prefix Collision Check
    full_input_hash = snapshot.get("inferenceInputHash") or snapshot.get("inference_input_hash")
    input_hash = snapshot.get("inputHash") or snapshot.get("input_hash")

    if full_input_hash is not None:
        if not isinstance(full_input_hash, str) or not re.match(r"^[a-f0-9]{64}$", full_input_hash, re.IGNORECASE):
            raise SnapshotValidationError(
                "INVALID_INFERENCE_INPUT_HASH",
                f"Snapshot inferenceInputHash must be a 64-character hex string, got '{full_input_hash}'."
            )
        if input_hash:
            if not isinstance(input_hash, str) or input_hash.lower() != full_input_hash[:16].lower():
                raise SnapshotValidationError(
                    "PREFIX_COLLISION_MISMATCH",
                    f"Prefix collision / identity mismatch: inputHash ('{input_hash}') does not match inferenceInputHash[:16] ('{full_input_hash[:16]}')."
                )

    full_output_hash = snapshot.get("predictionOutputHash") or snapshot.get("prediction_output_hash")
    if full_output_hash is not None:
        if not isinstance(full_output_hash, str) or not re.match(r"^[a-f0-9]{64}$", full_output_hash, re.IGNORECASE):
            raise SnapshotValidationError(
                "INVALID_PREDICTION_OUTPUT_HASH",
                f"Snapshot predictionOutputHash must be a 64-character hex string, got '{full_output_hash}'."
            )

    if input_hash is not None:
        if not isinstance(input_hash, str) or not re.match(r"^[a-f0-9]{16,64}$", input_hash, re.IGNORECASE):
            raise SnapshotValidationError(
                "INVALID_INPUT_HASH",
                "Snapshot inputHash must be a valid hexadecimal string (16-64 characters)."
            )
    elif require_all_fields:
        raise SnapshotValidationError("MISSING_REQUIRED_FIELD", "Snapshot missing required field 'inputHash'.")

    # 2. Stage & Penalties
    stage = snapshot.get("stage")
    if stage != "provisional":
        raise SnapshotValidationError("UNSUPPORTED_STAGE", f"Dry-run snapshot stage must be 'provisional', got '{stage}'.")
    quali_status = snapshot.get("qualifyingStatus", {})
    if not isinstance(quali_status, dict):
        raise SnapshotValidationError("MALFORMED_QUALIFYING_STATUS", "qualifyingStatus must be a dictionary.")
    if quali_status.get("hasPenaltiesApplied") is not False:
        raise SnapshotValidationError(
            "CONTRADICTORY_STAGE_METADATA",
            "Stage 'provisional' strictly requires hasPenaltiesApplied to be False."
        )

    # 3. Generation Timestamp
    ts_str = snapshot.get("generatedAtUtc")
    if not ts_str or not isinstance(ts_str, str):
        raise SnapshotValidationError("MISSING_TIMESTAMP", "generatedAtUtc must be a non-empty string.")
    try:
        # Normalize trailing Z for Python fromisoformat
        clean_ts = ts_str.replace("Z", "+00:00")
        dt = datetime.fromisoformat(clean_ts)
    except Exception as e:
        raise SnapshotValidationError("INVALID_TIMESTAMP_FORMAT", f"Invalid ISO 8601 UTC timestamp '{ts_str}': {str(e)}")

    if dt.year < 2000 or dt.year > 2050:
        raise SnapshotValidationError("TIMESTAMP_OUT_OF_BOUNDS", f"Timestamp year {dt.year} outside [2000, 2050].")

    # 4. Provenance
    prov = snapshot.get("provenance")
    if not isinstance(prov, dict) or not prov:
        raise SnapshotValidationError("MISSING_PROVENANCE", "Snapshot missing required provenance dictionary.")
    if not (prov.get("qualifyingSource") or prov.get("baselineVersion")):
        raise SnapshotValidationError("INSUFFICIENT_PROVENANCE", "Provenance must cite qualifying source or baseline.")

    # 5. Predictions & Roster
    predictions = snapshot.get("predictions")
    if not isinstance(predictions, list) or len(predictions) == 0:
        raise SnapshotValidationError("EMPTY_PREDICTIONS", "Predictions array is empty or not a list.")

    expected_roster = snapshot.get("expectedRoster")
    if not isinstance(expected_roster, list) or len(expected_roster) == 0:
        raise SnapshotValidationError("EMPTY_EXPECTED_ROSTER", "expectedRoster must be a non-empty list.")

    seen_drivers = set()
    total_prob = 0.0

    for p in predictions:
        driver_id = p.get("driverId")
        if not driver_id or not isinstance(driver_id, str):
            raise SnapshotValidationError("INVALID_DRIVER_ID", "Driver prediction entry missing valid driverId.")
        if driver_id in seen_drivers:
            raise SnapshotValidationError("DUPLICATE_DRIVER_ID", f"Duplicate driverId '{driver_id}' in predictions.")
        seen_drivers.add(driver_id)

        if driver_id not in expected_roster:
            raise SnapshotValidationError("UNKNOWN_DRIVER", f"Driver '{driver_id}' not in expected roster.")

        prob = p.get("winProbability")
        if prob is None or not np.isfinite(prob):
            raise SnapshotValidationError("NON_FINITE_PROBABILITY", f"Non-finite probability for '{driver_id}'.")
        if prob < 0.0 or prob > 1.0:
            raise SnapshotValidationError("PROBABILITY_OUT_OF_BOUNDS", f"Probability {prob} outside [0, 1] for '{driver_id}'.")
        total_prob += prob

    for exp_id in expected_roster:
        if exp_id not in seen_drivers:
            raise SnapshotValidationError("MISSING_DRIVER", f"Expected driver '{exp_id}' missing from predictions.")

    if len(predictions) != len(expected_roster):
        raise SnapshotValidationError(
            "ROSTER_COUNT_MISMATCH",
            f"Prediction count ({len(predictions)}) does not match expected roster count ({len(expected_roster)})."
        )

    # Probability sum tolerance (+/- 0.005)
    if abs(total_prob - 1.0) > 0.005:
        raise SnapshotValidationError(
            "PROBABILITY_SUM_OUT_OF_BOUNDS",
            f"Probabilities sum to {total_prob:.6f}, expected 1.0 (+/- 0.005)."
        )

    # 6. Predicted Winner
    winner = snapshot.get("predictedWinner")
    if not isinstance(winner, dict):
        raise SnapshotValidationError("MISSING_PREDICTED_WINNER", "predictedWinner must be a dictionary.")

    sorted_preds = sorted(predictions, key=lambda d: d.get("winProbability", 0.0), reverse=True)
    top_pred = sorted_preds[0]

    if winner.get("driverId") != top_pred.get("driverId"):
        raise SnapshotValidationError(
            "WINNER_MISMATCH",
            f"predictedWinner '{winner.get('driverId')}' does not match highest probability driver '{top_pred.get('driverId')}'."
        )
    if abs(winner.get("winProbability", 0.0) - top_pred.get("winProbability", 0.0)) > 1e-4:
        raise SnapshotValidationError(
            "WINNER_PROBABILITY_MISMATCH",
            "predictedWinner winProbability does not match top driver probability."
        )

    # 7. Regulation Era Warning (for 2026)
    if snapshot.get("season") == 2026:
        reg_warn = snapshot.get("regulationEraWarning", {})
        if reg_warn.get("isUnknownRegulationEra") is not True or reg_warn.get("warningCode") != "UNVALIDATED_2026_REGULATIONS":
            raise SnapshotValidationError(
                "INVALID_2026_REGULATION_WARNING",
                "2026 snapshot must include UNVALIDATED_2026_REGULATIONS warning."
            )


