def sanitize_canonical_value(val: Any) -> Any:
    """Sanitizes values for deterministic canonical JSON serialization."""
    if val is None:
        return None
    if isinstance(val, (bool, np.bool_)):
        return bool(val)
    if isinstance(val, (int, np.integer)):
        return int(val)
    if isinstance(val, (float, np.floating)):
        if np.isnan(val):
            return "NaN"
        if np.isinf(val):
            return "Infinity" if val > 0 else "-Infinity"
        return float(val)
    return str(val)


def compute_canonical_inference_input_hash(
    race_id: str,
    season: int,
    round_num: int,
    circuit_id: str,
    stage: str,
    driver_rows: List[Dict[str, Any]],
    model_version: str = MODEL_VERSION_TAG,
    feature_schema_version: str = FEATURE_SCHEMA_VERSION,
    baseline_version: str = BASELINE_VERSION_TAG,
    baseline_alpha: float = BASELINE_ALPHA,
    hybrid_formula_version: str = HYBRID_FORMULA_VERSION_TAG,
    blend_weight: float = HYBRID_BLEND_WEIGHT,
    p_floor: float = P_FLOOR,
    ml_temperature: float = ML_TEMPERATURE,
    combination_method: str = "geometric"
) -> Tuple[str, Dict[str, Any]]:
    """
    Computes deterministic SHA-256 hash (64 hex characters) of canonical inference inputs.
    Permutation invariant via lexicographical sorting by driver_id.
    """
    stage_clean = str(stage).strip().lower()

    sorted_drivers = []
    for d in driver_rows:
        d_id = str(d.get("driver_id", d.get("driverId", ""))).strip().lower()
        if not d_id:
            raise HybridInferenceError("INVALID_DRIVER_ID", "Driver record missing driver_id.")

        raw_feats = d.get("features", d)
        driver_feature_vector = []
        for feat_name in ALL_MODEL_FEATURES:
            val = raw_feats.get(feat_name, None)
            driver_feature_vector.append({
                "name": feat_name,
                "value": sanitize_canonical_value(val)
            })

        sorted_drivers.append({
            "driver_id": d_id,
            "features_42": driver_feature_vector
        })

    sorted_drivers = sorted(sorted_drivers, key=lambda x: x["driver_id"])

    canonical_payload = {
        "race_identity": {
            "circuit_id": str(circuit_id).strip().lower(),
            "prediction_stage": stage_clean,
            "race_id": str(race_id).strip().lower(),
            "round": int(round_num),
            "season": int(season)
        },
        "model_metadata": {
            "baseline_alpha": float(baseline_alpha),
            "baseline_version": str(baseline_version).strip(),
            "feature_schema_version": str(feature_schema_version).strip(),
            "hybrid_blend_weight": float(blend_weight),
            "hybrid_formula_version": str(hybrid_formula_version).strip(),
            "model_version": str(model_version).strip(),
            "inference_config": {
                "combination_method": str(combination_method),
                "ml_temperature": float(ml_temperature),
                "p_floor": float(p_floor)
            }
        },
        "roster_identity": {
            "driver_count": len(sorted_drivers),
            "driver_ids_sorted": [d["driver_id"] for d in sorted_drivers]
        },
        "drivers": sorted_drivers
    }

    canonical_json = json.dumps(canonical_payload, sort_keys=True, separators=(",", ":"))
    full_sha256 = hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()
    return full_sha256, canonical_payload


def compute_canonical_prediction_output_hash(
    race_id: str,
    season: int,
    round_num: int,
    circuit_id: str,
    stage: str,
    predictions: List[Dict[str, Any]],
    model_version: str = MODEL_VERSION_TAG,
    baseline_version: str = BASELINE_VERSION_TAG,
    hybrid_formula_version: str = HYBRID_FORMULA_VERSION_TAG
) -> Tuple[str, Dict[str, Any]]:
    """
    Computes deterministic SHA-256 hash (64 hex characters) of prediction output distribution.
    Decoupled from underlying feature inputs.
    Permutation invariant via lexicographical sorting by driver_id.
    """
    stage_clean = str(stage).strip().lower()

    sorted_preds = []
    for p in predictions:
        d_id = str(p.get("driver_id", p.get("driverId", ""))).strip().lower()
        if not d_id:
            raise HybridInferenceError("INVALID_DRIVER_ID", "Prediction record missing driver_id.")

        g_pos = int(p.get("grid_position", p.get("gridPosition", 20)))
        p_grid = float(p.get("grid_baseline_probability", p.get("gridBaselineProbability", 0.0)))
        p_ml = float(p.get("ml_win_probability", p.get("mlWinProbability", 0.0)))
        p_hybrid = float(p.get("hybrid_win_probability", p.get("hybridWinProbability", p.get("winProbability", 0.0))))

        sorted_preds.append({
            "driver_id": d_id,
            "grid_position": g_pos,
            "grid_win_probability": sanitize_canonical_value(p_grid),
            "ml_win_probability": sanitize_canonical_value(p_ml),
            "hybrid_win_probability": sanitize_canonical_value(p_hybrid)
        })

    sorted_preds = sorted(sorted_preds, key=lambda x: x["driver_id"])

    canonical_payload = {
        "race_identity": {
            "circuit_id": str(circuit_id).strip().lower(),
            "prediction_stage": stage_clean,
            "race_id": str(race_id).strip().lower(),
            "round": int(round_num),
            "season": int(season)
        },
        "model_metadata": {
            "baseline_version": str(baseline_version).strip(),
            "hybrid_formula_version": str(hybrid_formula_version).strip(),
            "model_version": str(model_version).strip()
        },
        "roster_identity": {
            "driver_count": len(sorted_preds),
            "driver_ids_sorted": [p["driver_id"] for p in sorted_preds]
        },
        "predictions": sorted_preds
    }

    canonical_json = json.dumps(canonical_payload, sort_keys=True, separators=(",", ":"))
    full_sha256 = hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()
    return full_sha256, canonical_payload


