# Empirical Grid Baseline Model
# -----------------------------------------------------------------------------
class EmpiricalGridBaseline:
    """
    Authoritative reference empirical grid baseline model.
    Trained on 2021-2023 historical data (66 races).
    Applies Laplace smoothing with alpha=1.0 and prior win rate p0 = 1/20 = 0.05.
    Enforces floor p_floor = 0.0005 and exact simplex normalization.
    """
    def __init__(
        self,
        smoothing: float = BASELINE_ALPHA,
        p_floor: float = P_FLOOR,
        version_tag: str = BASELINE_VERSION_TAG
    ):
        self.smoothing = float(smoothing)
        self.p_floor = float(p_floor)
        self.version_tag = version_tag
        self.grid_wins: Dict[int, int] = {g: 0 for g in range(1, 25)}
        self.grid_starts: Dict[int, int] = {g: 0 for g in range(1, 25)}
        self.total_races: int = 0
        self.overall_win_rate: float = 0.05
        self.is_fitted: bool = False

    def fit(self, train_df: pd.DataFrame, target_col: str = "won_race") -> "EmpiricalGridBaseline":
        """Fits historical win and start counts per grid position."""
        if train_df is None or train_df.empty:
            raise HybridInferenceError("BASELINE_TRAIN_EMPTY", "Training DataFrame for empirical baseline is empty.")

        self.total_races = int(train_df["race_id"].nunique())
        wins_dict = train_df.groupby("grid_position")[target_col].sum().to_dict()
        starts_dict = train_df.groupby("grid_position")[target_col].count().to_dict()

        for g in range(1, 25):
            self.grid_wins[g] = int(wins_dict.get(g, 0))
            self.grid_starts[g] = int(starts_dict.get(g, 0))

        median_starters = float(train_df.groupby("race_id")["driver_id"].count().median())
        self.overall_win_rate = 1.0 / max(1.0, median_starters)
        self.is_fitted = True
        return self

    def predict_race_probabilities(self, race_df: pd.DataFrame) -> np.ndarray:
        """
        Computes calibrated empirical win probabilities for all starters in race_df.
        Clamps grid positions to [1, 24] and falls back to grid 20 for missing/invalid.
        Normalizes across the field to sum to 1.0.
        """
        if not self.is_fitted:
            raise HybridInferenceError("BASELINE_NOT_FITTED", "EmpiricalGridBaseline must be fitted before predict.")

        n = len(race_df)
        if n == 0:
            raise HybridInferenceError("EMPTY_RACE_DF", "Cannot predict baseline on empty race DataFrame.")

        raw_probs = np.zeros(n, dtype=np.float64)
        for i, (_, row) in enumerate(race_df.iterrows()):
            try:
                g = int(row.get("grid_position", 20))
            except (ValueError, TypeError):
                g = 20
            g = max(1, min(24, g))
            w = self.grid_wins.get(g, 0)
            c = self.grid_starts.get(g, 0)
            smoothed = (w + self.smoothing * self.overall_win_rate) / (c + self.smoothing)
            raw_probs[i] = max(self.p_floor, smoothed)

        total = np.sum(raw_probs)
        if total <= 0 or not np.isfinite(total):
            raise HybridInferenceError("NON_FINITE_BASELINE", f"Baseline raw probability sum invalid: {total}.")

        return raw_probs / total


