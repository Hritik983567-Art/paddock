# Geometric Hybrid Engine
# -----------------------------------------------------------------------------
class GeometricHybridEngine:
    """
    Log-space geometric fusion engine:
       P_hybrid(i) proportional to (P_grid(i)**(1 - w)) * (P_ML(i)**w)
    Uses logsumexp for numerical stability and prevents underflow.
    """
    def __init__(
        self,
        weight: float = HYBRID_BLEND_WEIGHT,
        p_floor: float = P_FLOOR,
        hybrid_formula_version: str = HYBRID_FORMULA_VERSION_TAG
    ):
        self.weight = float(np.clip(weight, 0.0, 1.0))
        self.p_floor = float(p_floor)
        self.hybrid_formula_version = hybrid_formula_version

    def combine_probabilities(
        self,
        p_grid: np.ndarray,
        p_ml: np.ndarray
    ) -> np.ndarray:
        """
        Combines P_grid and P_ML using log-space geometric weighting.
        Enforces unit simplex normalization and floor protection.
        """
        n = len(p_grid)
        if n == 0 or len(p_ml) != n:
            raise HybridInferenceError(
                "DIMENSION_MISMATCH",
                f"Array length mismatch: p_grid={len(p_grid)}, p_ml={len(p_ml)}."
            )

        if not np.all(np.isfinite(p_grid)) or np.any(p_grid < 0.0):
            raise HybridInferenceError("NON_FINITE_PROBABILITY", "Non-finite or negative probability in P_grid.")
        if not np.all(np.isfinite(p_ml)) or np.any(p_ml < 0.0):
            raise HybridInferenceError("NON_FINITE_PROBABILITY", "Non-finite or negative probability in P_ML.")

        # Floor protection before log
        p_g = np.clip(np.asarray(p_grid, dtype=np.float64), self.p_floor, 1.0)
        p_g = p_g / np.sum(p_g)

        p_m = np.clip(np.asarray(p_ml, dtype=np.float64), self.p_floor, 1.0)
        p_m = p_m / np.sum(p_m)

        w = self.weight
        log_p_g = np.log(p_g)
        log_p_m = np.log(p_m)

        log_unnorm = (1.0 - w) * log_p_g + w * log_p_m
        log_z = logsumexp(log_unnorm)
        p_hybrid = np.exp(log_unnorm - log_z)

        # Enforce exact unit sum
        total = np.sum(p_hybrid)
        if total <= 0 or not np.isfinite(total):
            raise HybridInferenceError("NON_FINITE_HYBRID", f"Hybrid probability sum invalid: {total}.")

        return p_hybrid / total


