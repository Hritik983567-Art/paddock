_default_engine_cache: Optional[HybridRaceInferenceEngine] = None

def load_default_hybrid_engine(
    model_bundle_path: Optional[str] = None,
    metadata_path: Optional[str] = None,
    dataset_path: Optional[str] = None
) -> HybridRaceInferenceEngine:
    """
    Loads and fits the default HybridRaceInferenceEngine using:
    - LightGBM model from models/predictor/v1.0.0/trained_models.joblib
    - Metadata from models/predictor/v1.0.0/model_metadata.json
    - EmpiricalGridBaseline fitted on 2021-2023 of data/predictor/f1_race_predictor_dataset.csv
    """
    global _default_engine_cache
    if _default_engine_cache is not None and model_bundle_path is None:
        return _default_engine_cache

    resolved_bundle = model_bundle_path or os.path.join(MODELS_ROOT_DIR, MODEL_VERSION, "trained_models.joblib")
    resolved_meta = metadata_path or os.path.join(MODELS_ROOT_DIR, MODEL_VERSION, "model_metadata.json")
    resolved_dataset = dataset_path or DATASET_CSV_PATH

    if not os.path.exists(resolved_bundle):
        raise HybridInferenceError("MODEL_ARTIFACT_MISSING", f"Trained model bundle missing at {resolved_bundle}")
    if not os.path.exists(resolved_meta):
        raise HybridInferenceError("METADATA_MISSING", f"Model metadata missing at {resolved_meta}")
    if not os.path.exists(resolved_dataset):
        raise HybridInferenceError("DATASET_MISSING", f"Historical dataset missing at {resolved_dataset}")

    # Load LightGBM model
    bundle = joblib.load(resolved_bundle)
    lgb_model = bundle.get("lightgbm")
    if lgb_model is None:
        raise HybridInferenceError("MODEL_CORRUPT", "LightGBM model candidate missing from bundle.")

    # Load metadata
    with open(resolved_meta, "r", encoding="utf-8") as f:
        meta = json.load(f)

    # Fit EmpiricalGridBaseline on 2021-2023 historical data
    df_hist = pd.read_csv(resolved_dataset)
    train_slice = df_hist[(df_hist["season"] >= 2021) & (df_hist["season"] <= 2023)]
    baseline = EmpiricalGridBaseline(smoothing=BASELINE_ALPHA, p_floor=P_FLOOR)
    baseline.fit(train_slice)

    hybrid_engine = GeometricHybridEngine(weight=HYBRID_BLEND_WEIGHT, p_floor=P_FLOOR)
    engine = HybridRaceInferenceEngine(
        ml_model=lgb_model,
        metadata=meta,
        baseline=baseline,
        hybrid_engine=hybrid_engine,
        ml_temperature=ML_TEMPERATURE
    )
    if model_bundle_path is None:
        _default_engine_cache = engine
    return engine


def run_hybrid_inference_for_race(
    race_id: str,
    stage: str = STAGE_PROVISIONAL,
    output_dir: Optional[str] = None,
    baseline_path: Optional[str] = None,
    dry_run: bool = True
) -> Dict[str, Any]:
    """
    Executes end-to-end hybrid prediction for an explicit race using LiveFeatureBuilder.
    Writes canonical snapshot artifact atomically to output_dir.
    """
    if not dry_run:
        raise HybridInferenceError("LIVE_WRITES_FORBIDDEN", "Phase 3C.4F.3 permits only dry-run execution.")

    from scripts.predictor_pipeline.run_inference_snapshot import (
        parse_race_id,
        validate_dry_run_snapshot
    )
    from scripts.predictor_pipeline.live_feature_builder import LiveFeatureBuilder

    season, round_num, _ = parse_race_id(race_id)

    # Assembly from verified baseline via LiveFeatureBuilder
    default_baseline = os.path.join(OUTPUT_DIR, "historical_baseline_2025_2026.json")
    resolved_baseline = baseline_path or default_baseline
    if not os.path.exists(resolved_baseline):
        raise HybridInferenceError("BASELINE_FILE_MISSING", f"Baseline file missing at '{resolved_baseline}'.")

    builder = LiveFeatureBuilder(baseline_path=resolved_baseline, validate_schema=True)
    feature_result = builder.build_features_for_race(season=season, round_num=round_num, stage=stage)

    engine = load_default_hybrid_engine()
    result = engine.predict_race(
        features_df=feature_result.features_df,
        metadata_df=feature_result.metadata_df,
        stage=stage
    )

    snapshot_payload = engine.to_canonical_snapshot(
        result,
        qualifying_provenance=feature_result.diagnostics.get("qualifying_provenance", "historical_baseline_v1.3.1")
    )

    # Validate against canonical dry-run snapshot schema
    validate_dry_run_snapshot(snapshot_payload, require_all_fields=True)

    # Atomic write to output_dir
    resolved_output_dir = os.path.abspath(output_dir or os.path.join(PROJECT_ROOT, "artifacts", "dry_run_snapshots"))
    prod_snapshot_dir = os.path.abspath(os.path.join(PROJECT_ROOT, "data", "predictor", "snapshots"))

    if resolved_output_dir == prod_snapshot_dir or resolved_output_dir.startswith(prod_snapshot_dir + os.sep):
        raise HybridInferenceError(
            "FORBIDDEN_OUTPUT_DIRECTORY",
            f"Refusing to write into production snapshot directory '{prod_snapshot_dir}'."
        )
    os.makedirs(resolved_output_dir, exist_ok=True)

    dest_filename = f"{result.race_id}_{stage}_{MODEL_VERSION_TAG}_hybrid_{result.input_hash}.json"
    dest_path = os.path.join(resolved_output_dir, dest_filename)

    temp_path = dest_path + f".tmp.{os.getpid()}"
    try:
        with open(temp_path, "w", encoding="utf-8") as f:
            json.dump(snapshot_payload, f, indent=2)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp_path, dest_path)
    except Exception as e:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise HybridInferenceError("OUTPUT_WRITE_FAILED", f"Atomic write failed: {str(e)}")

    return {
        "status": "success",
        "result": result,
        "snapshot": snapshot_payload,
        "artifact_path": dest_path,
        "artifact_filename": dest_filename,
        "input_hash": result.input_hash,
        "inference_input_hash": result.inference_input_hash,
        "prediction_output_hash": result.prediction_output_hash,
        "predicted_winner": result.predicted_winner["driverId"],
        "winner_prob": result.predicted_winner["winProbability"]
    }
